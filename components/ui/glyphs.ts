/* Набор символов — второй «шрифт» сайта. Используется в полях символов,
   маркерах секций, ленте и анимации заголовков. */
export const GLYPHS = ['※', '⁂', '§', '¶', '†', '‡', '✺', '◉', '∴', '⌖', '✚', '◆', '☉', '⌘', '✦', '⊕', '№', '⸸', '☍', '∞'];

/** Детерминированный генератор: одинаковый результат на сервере и клиенте. */
export function rng(seed: number) {
  let s = seed >>> 0 || 1;
  return () => {
    s ^= s << 13;
    s ^= s >>> 17;
    s ^= s << 5;
    return ((s >>> 0) % 10000) / 10000;
  };
}

export const glyphAt = (i: number) => GLYPHS[((i % GLYPHS.length) + GLYPHS.length) % GLYPHS.length];
